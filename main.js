function wrapText(text, maxLen) {
  if (text.length <= maxLen)
    return [text];
  const words = text.split(" ");
  const lines = [];
  let cur = "";
  for (const w of words) {
    const test = cur ? cur + " " + w : w;
    if (test.length > maxLen && cur) {
      lines.push(cur);
      cur = w;
    } else
      cur = test;
  }
  if (cur)
    lines.push(cur);
  return lines;
}
